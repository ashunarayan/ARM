def rg(a, b):
    """win-count range 'a--b', or a single number when both ends are equal"""
    a, b = int(a), int(b)
    return f"{a}" if a == b else f"{a}--{b}"


def r2(n):
    return pd.read_csv(os.path.join(V2, n))


def r3(n):
    return pd.read_csv(os.path.join(V3, n))


def write(name, body):
    with open(os.path.join(TABLES, name), "w", encoding="utf-8") as f:
        f.write("% AUTO-GENERATED by research_rescue/make_tables_v3.py from results/v2 and results/v3 - do not edit by hand.\n" + body)


def pooled(D, keys):
    D = D.assign(w=D.seg_mae * D.n_seg)
    a = D.groupby(keys + ["draw"]).agg(w=("w", "sum"), n=("n_seg", "sum"), within=("seg_mae", "mean")).reset_index()
    a["mae"] = a.w / a.n
    return a


