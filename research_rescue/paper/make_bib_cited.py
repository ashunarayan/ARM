"""Write paper/references_cited.tex: only the entries of references/references.tex that the paper cites, numbered in
order of first citation (IEEE style). Fails loudly if a cited key has no entry."""
from __future__ import annotations

import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))


def expand(path, seen=None):
    """Concatenate a .tex file with its \\input files, in document order."""
    seen = seen or set()
    txt = open(path, encoding="utf-8").read()
    txt = re.sub(r"(?<!\\)%.*", "", txt)

    def rep(m):
        name = m.group(1)
        if name in ("numbers.tex", "references_cited.tex") or name.startswith("../"):
            return ""
        p = os.path.join(HERE, name if name.endswith(".tex") else name + ".tex")
        return expand(p, seen) if os.path.exists(p) and p not in seen else ""
    return re.sub(r"\\input\{([^}]*)\}", rep, txt)


def main(doc="main.tex", out="references_cited.tex"):
    body = expand(os.path.join(HERE, doc))
    order = []
    for grp in re.findall(r"\\cite\{([^}]*)\}", body):
        for k in grp.split(","):
            k = k.strip()
            if k and k not in order:
                order.append(k)
    bib = open(os.path.join(HERE, "..", "references", "references.tex"), encoding="utf-8").read()
    bib = re.sub(r"\\(begin|end)\{thebibliography\}(\{[^}]*\})?", "", bib)
    items = {}
    for chunk in bib.split("\\bibitem{")[1:]:
        key = chunk[:chunk.index("}")]
        items[key] = "\\bibitem{" + chunk.strip()
    missing = [k for k in order if k not in items]
    if missing:
        sys.exit(f"cited but not in references.tex: {missing}")
    with open(os.path.join(HERE, out), "w", encoding="utf-8") as f:
        f.write("% AUTO-GENERATED by paper/make_bib_cited.py from references/references.tex (cited entries, citation order)\n")
        f.write("\\begin{thebibliography}{%d}\n" % len(order))
        for k in order:
            f.write(items[k].rstrip() + "\n\n")
        f.write("\\end{thebibliography}\n")
    print(f"{len(order)} cited references written to {out}; unused entries: {sorted(set(items) - set(order))}")


if __name__ == "__main__":
    main(*sys.argv[1:])
